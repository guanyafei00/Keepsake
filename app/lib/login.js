// B 站扫码登录：BrowserWindow 加载官方登录页（passport.bilibili.com），用户扫码确认后
// 从该窗口 session 提取 cookie 写 Netscape 格式 cookies.txt。
// 下游（yt-dlp --cookies / gallery-dl --cookies / bili-probe 参数）读同一文件，自动生效。
// 关键设计：登录页 + cookie 下发全程走 Chromium 网络栈——完全绕开 Node 直连 B 站的 TLS 指纹风控。
// cookie 存 userData/cookies.txt（打包态 asar 内 resources 不可写）。
const { BrowserWindow, session } = require('electron');
const fs = require('fs');
const path = require('path');

const LOGIN_URL = 'https://passport.bilibili.com/login';
const PARTITION = 'persist:bilibili-login';   // 持久 session：下次登录窗口保留浏览器侧 cookie

let win = null;

function cookieFile(userData) { return path.join(userData, 'cookies.txt'); }

// session cookies → Netscape 格式文本（7 列 tab 分隔，yt-dlp/gallery-dl/探针通吃）
async function sessionToNetscape(ses) {
  const cookies = await ses.cookies.get({ domain: 'bilibili.com' });
  const lines = ['# Netscape HTTP Cookie File', '# Generated by Keepsake login'];
  for (const c of cookies) {
    if (!/bilibili\.com$/.test(c.domain)) continue;
    const domain = c.domain.startsWith('.') ? c.domain : '.' + c.domain;
    lines.push([domain, 'TRUE', c.path || '/', c.secure ? 'TRUE' : 'FALSE',
      c.expirationDate ? Math.floor(c.expirationDate) : 2147483647, c.name, c.value].join('\t'));
  }
  return lines.join('\n') + '\n';
}

// 打开登录窗口。onDone({ok, reason?|cookieFile?}) 只回调一次
function openLoginWindow(userData, onDone) {
  if (win && !win.isDestroyed()) {
    win.focus();
    return { ok: false, reason: '登录窗口已打开' };
  }
  win = new BrowserWindow({
    width: 430, height: 580, title: '登录 B 站（扫码或账号登录）',
    autoHideMenuBar: true,
    webPreferences: { partition: PARTITION, contextIsolation: true, nodeIntegration: false }
  });
  win.loadURL(LOGIN_URL);
  // 导航限制（登录窗口只许访问 B 站域名，防 passport 页外链跳去任意站点
  win.webContents.on('will-navigate', (e, url) => {
    if (!/^https:\/\/([a-z0-9-]+\.)*bilibili\.com/i.test(url)) e.preventDefault();
  });

  let settled = false;
  let poll = null;

  const finish = async (ok) => {
    if (settled) return;
    settled = true;
    if (poll) clearInterval(poll);
    try {
      if (ok) {
        const txt = await sessionToNetscape(win.webContents.session);
        if (!txt.includes('SESSDATA')) return onDone({ ok: false, reason: '未检测到登录凭证（SESSDATA）' });
        fs.writeFileSync(cookieFile(userData), txt);
        onDone({ ok: true, cookieFile: cookieFile(userData) });
      } else {
        onDone({ ok: false, reason: '已取消' });
      }
    } catch (e) {
      onDone({ ok: false, reason: String(e.message || e).slice(0, 120) });
    } finally {
      if (win && !win.isDestroyed()) win.destroy();
      win = null;
    }
  };

  // 轮询检测 SESSDATA：扫码确认后 B 站前端直接种 cookie，无需拦截任何跳转
  poll = setInterval(async () => {
    if (!win || win.isDestroyed()) return;
    try {
      const cookies = await win.webContents.session.cookies.get({ domain: 'bilibili.com' });
      if (cookies.some(c => c.name === 'SESSDATA' && c.value)) finish(true);
    } catch (e) { /* session 短暂不可用，下轮再查 */ }
  }, 1500);

  win.on('closed', () => {
    if (!settled) { settled = true; if (poll) clearInterval(poll); onDone({ ok: false, reason: '已取消' }); }
    win = null;
  });

  return { ok: true };
}

// 当前登录态：cookies.txt 是否含 SESSDATA（顺带取 DedeUserID 当 uid）
function loginState(userData) {
  try {
    const txt = fs.readFileSync(cookieFile(userData), 'utf-8');
    let loggedIn = false, uid = null;
    for (const line of txt.split('\n')) {
      const p = line.split('\t');
      if (p.length < 7) continue;
      if (p[5] === 'SESSDATA' && p[6].trim()) loggedIn = true;
      if (p[5] === 'DedeUserID') uid = p[6].trim();
    }
    return { loggedIn, uid };
  } catch (e) { return { loggedIn: false, uid: null }; }
}

// 退出登录：删 cookies.txt + 清登录 session 的 bilibili cookie
async function logout(userData) {
  try { fs.unlinkSync(cookieFile(userData)); } catch (e) {}
  try {
    const ses = session.fromPartition(PARTITION);
    const cookies = await ses.cookies.get({ domain: 'bilibili.com' });
    for (const c of cookies) {
      // 非点前缀域名（如 passport.bilibili.com）不能 slice(1)，否则拼出非法 URL 删不掉（
      const host = c.domain.startsWith('.') ? c.domain.slice(1) : c.domain;
      try { await ses.cookies.remove('https://' + host, c.name); } catch (e) {}
    }
  } catch (e) {}
  return { ok: true };
}

module.exports = { openLoginWindow, loginState, logout, cookieFile };
